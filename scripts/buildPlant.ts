/**
 * Roadworks plant pipeline: `npm run plant [-- <sourceDir>]`
 *
 * Builds the lane closures' plant from Sketchfab models (CC BY 4.0, credited
 * in PLANT_CREDITS and README "Roadworks plant"):
 *
 *  1. scripts/blender/plantPack.py (Blender in background mode) simplifies
 *     each model to its triangle budget, bakes its flat material colors into
 *     vertex colors under one material and measures the boxes the sim
 *     collides with.
 *  2. The GLB is optimized with glTF Transform (dedup, weld, Meshopt) into
 *     public/plant/plant.glb.
 *  3. src/assets/plantModels.json gets each piece's boxes, beacon and
 *     triangles, plus the credits, for the renderer (render/districts/
 *     roadworks.ts) and the test that holds the sim's PLANT boxes
 *     (city/districts/roadworks.ts) to the models.
 *
 * <sourceDir> (default assets/source/excavator) holds each model as
 * Sketchfab's download imported into Blender and exported to GLB
 * (excavator.glb). Downloading needs a Sketchfab account, so keep it.
 */
import { mkdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { PropertyType } from '@gltf-transform/core';
import { EXTMeshoptCompression } from '@gltf-transform/extensions';
import { dedup, meshopt, prune, weld } from '@gltf-transform/functions';
import { MeshoptEncoder } from 'meshoptimizer';
import { createIO } from './inspectAsset';
import { findBlender, triangleCount } from './gltfUtil';

const ROOT = process.cwd();
const SRC = process.argv[2] ?? join(ROOT, 'assets/source/excavator');
const OUT = join(ROOT, 'public/plant');
const JSON_PATH = join(ROOT, 'src/assets/plantModels.json');

/** Where every piece of plant comes from; the credits screen and README read the same list. */
export const PLANT_CREDITS = [
  {
    title: 'Excavator',
    creator: 'MD.Jobair Hossain',
    creatorUrl: 'https://sketchfab.com/samrat33k',
    url: 'https://sketchfab.com/3d-models/excavator-c00f6295235349e3b60885a9efa45629',
    license: 'CC BY 4.0',
    licenseUrl: 'https://creativecommons.org/licenses/by/4.0/',
    changes: 'Simplified, colors baked to the vertices, cab glass made opaque',
    pieces: ['excavator'],
  },
];

async function main(): Promise<void> {
  const work = join(tmpdir(), 'street-scene-plant');
  mkdirSync(work, { recursive: true });
  const run = spawnSync(findBlender(), ['-b', '--factory-startup', '--python', join(ROOT, 'scripts/blender/plantPack.py'), '--', SRC, work], { encoding: 'utf8', maxBuffer: 1 << 26 });
  const out = `${run.stdout}\n${run.stderr}`;
  for (const line of out.split('\n')) if (/tris|Error|Traceback/.test(line) && !/INFO/.test(line)) console.log(line);
  if (run.status !== 0 || /Traceback/.test(out)) throw new Error(`plantPack.py failed (sources in ${SRC}: README, "Roadworks plant")`);

  const io = await createIO();
  const doc = await io.read(join(work, 'plant.glb'));
  await doc.transform(dedup({ propertyTypes: [PropertyType.ACCESSOR, PropertyType.MESH] }), weld(), prune({ keepAttributes: true }));
  await MeshoptEncoder.ready;
  doc.createExtension(EXTMeshoptCompression);
  await doc.transform(meshopt({ encoder: MeshoptEncoder, level: 'medium' }));
  mkdirSync(OUT, { recursive: true });
  await io.write(join(OUT, 'plant.glb'), doc);

  const pieces = JSON.parse(readFileSync(join(work, 'plant.json'), 'utf8')) as Record<string, unknown>;
  writeFileSync(JSON_PATH, JSON.stringify({ _: 'Generated by npm run plant (scripts/buildPlant.ts); do not edit. Plant space: +z toward the dig, y up, origin at the body footprint center on the ground, m.', credits: PLANT_CREDITS, pieces }, null, 1) + '\n');
  console.log(`plant.glb ${(statSync(join(OUT, 'plant.glb')).size / 1024).toFixed(0)} KB, ${triangleCount(doc)} triangles; ${Object.keys(pieces).length} pieces`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
