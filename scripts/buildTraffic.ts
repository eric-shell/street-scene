/**
 * Traffic pipeline: `npm run traffic [-- <packDir>]`
 *
 * Builds the ambient traffic's vehicles from Comrade1280's two Sketchfab
 * packs (CC BY 4.0, credited in TRAFFIC_CREDITS and README "Credits"):
 *
 *  1. scripts/blender/trafficPack.py (Blender in background mode) cuts the 19
 *     vehicles out of the packs, simplifies them to the traffic triangle
 *     budgets, packs their textures into one atlas and finds their lamps.
 *  2. The GLB is optimized with glTF Transform (dedup, weld, Meshopt) into
 *     public/traffic/traffic.glb; the atlas goes to public/traffic/ as WebP.
 *  3. src/assets/trafficModels.json gets each kind's footprint, height,
 *     triangles, tint flag and lamps, plus the credits, for the renderer
 *     (render/traffic/traffic.ts) and the tests that hold the sim's kinds
 *     (drivingParams.json traffic.kinds) to the models.
 *
 * <packDir> (default assets/source/comrade1280) holds the packs as
 * passengerCarPack.glb and civilServicePack.glb: Sketchfab's glTF download of
 * each, imported into Blender and exported to GLB. The packs are not
 * re-downloadable without a Sketchfab account, so keep them.
 */
import { copyFileSync, existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { PropertyType } from '@gltf-transform/core';
import { EXTMeshoptCompression } from '@gltf-transform/extensions';
import { dedup, meshopt, prune, weld } from '@gltf-transform/functions';
import { MeshoptEncoder } from 'meshoptimizer';
import { createIO } from './inspectAsset';
import { findBlender, triangleCount } from './gltfUtil';

const ROOT = process.cwd();
const PACKS = process.argv[2] ?? join(ROOT, 'assets/source/comrade1280');
const OUT = join(ROOT, 'public/traffic');
const JSON_PATH = join(ROOT, 'src/assets/trafficModels.json');

/** Where every traffic vehicle comes from; the garage and README credits read the same list. */
export const TRAFFIC_CREDITS = [
  {
    title: 'Generic passenger car pack',
    creator: 'Comrade1280',
    creatorUrl: 'https://sketchfab.com/comrade1280',
    url: 'https://sketchfab.com/3d-models/generic-passenger-car-pack-20f9af9b8a404d5cb022ac6fe87f21f5',
    license: 'CC BY 4.0',
    licenseUrl: 'https://creativecommons.org/licenses/by/4.0/',
    changes: 'Nine of the ten cars (the sport car left out), simplified, textures repacked, paint made tintable',
    kinds: ['sedan', 'wagon', 'hatch', 'compact', 'coupe', 'minivan', 'pickup', 'suv', 'offroad'],
  },
  {
    title: 'Generic civil service vehicles pack',
    creator: 'Comrade1280',
    creatorUrl: 'https://sketchfab.com/comrade1280',
    url: 'https://sketchfab.com/3d-models/generic-civil-service-vehicles-pack-8ff2a13f30914932a70c7950cfa58465',
    license: 'CC BY 4.0',
    licenseUrl: 'https://creativecommons.org/licenses/by/4.0/',
    changes: 'All ten vehicles, simplified, textures repacked',
    kinds: ['taxi', 'police', 'ambulance', 'postvan', 'serviceTruck', 'towTruck', 'fireTruck', 'garbageTruck', 'cityBus', 'schoolBus'],
  },
];

async function main(): Promise<void> {
  // Blender's own message for a missing file is "Please select a file", which names nothing.
  const missing = ['passengerCarPack.glb', 'civilServicePack.glb'].filter((f) => !existsSync(join(PACKS, f)));
  if (missing.length) throw new Error(`missing ${missing.join(' and ')} in ${PACKS}: the Comrade1280 packs exported to GLB (README, "Traffic"); pass another folder with npm run traffic -- <packDir>`);
  const work = join(tmpdir(), 'street-scene-traffic');
  mkdirSync(work, { recursive: true });
  const run = spawnSync(findBlender(), ['-b', '--factory-startup', '--python', join(ROOT, 'scripts/blender/trafficPack.py'), '--', PACKS, work], { encoding: 'utf8', maxBuffer: 1 << 26, env: { ...process.env, NODE: process.execPath } });
  const out = `${run.stdout}\n${run.stderr}`;
  for (const line of out.split('\n')) if (/tris|atlas|paint|Error|Traceback/.test(line) && !/INFO/.test(line)) console.log(line);
  if (run.status !== 0 || /Traceback/.test(out)) throw new Error('trafficPack.py failed');

  const io = await createIO();
  const doc = await io.read(join(work, 'traffic.glb'));
  await doc.transform(dedup({ propertyTypes: [PropertyType.ACCESSOR, PropertyType.MESH] }), weld(), prune({ keepAttributes: true }));
  await MeshoptEncoder.ready;
  doc.createExtension(EXTMeshoptCompression);
  await doc.transform(meshopt({ encoder: MeshoptEncoder, level: 'medium' }));
  mkdirSync(OUT, { recursive: true });
  await io.write(join(OUT, 'traffic.glb'), doc);
  copyFileSync(join(work, 'trafficAtlas.webp'), join(OUT, 'trafficAtlas.webp'));

  const models = JSON.parse(readFileSync(join(work, 'traffic.json'), 'utf8')) as { paintRef: number; kinds: Record<string, unknown> };
  writeFileSync(JSON_PATH, JSON.stringify({ _: 'Generated by npm run traffic (scripts/buildTraffic.ts); do not edit. Car space: +z forward, y up, m.', paintRef: models.paintRef, credits: TRAFFIC_CREDITS, kinds: models.kinds }, null, 1) + '\n');
  const kb = (p: string) => `${(statSync(p).size / 1024).toFixed(0)} KB`;
  console.log(`traffic.glb ${kb(join(OUT, 'traffic.glb'))}, ${triangleCount(doc)} triangles; trafficAtlas.webp ${kb(join(OUT, 'trafficAtlas.webp'))}; ${Object.keys(models.kinds).length} kinds`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
